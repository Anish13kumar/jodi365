const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const badRequests = [];
page.on('response', r => { if (r.url().startsWith(base) && r.status() >= 400) badRequests.push({url:r.url(),status:r.status()}); });
await page.goto(base, { waitUntil: 'networkidle' });
await page.locator('h1').waitFor();
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: 'outputs/desktop-hero.png' });
for (let y = 0; y < await page.evaluate(() => document.body.scrollHeight); y += 700) { await page.evaluate(y => window.scrollTo(0,y),y); await page.waitForTimeout(75); }
