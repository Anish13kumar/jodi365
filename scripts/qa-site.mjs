assert('Press selection restores default article',await page.locator('.press-feature h3').innerText().then(text=>text.includes('accidental matchmaker')));
assert('13/4/4 credentials visible',await page.locator('.education-stats').innerText().then(text=>text.includes('13')&&text.toLowerCase().includes('degrees')&&text.toLowerCase().includes('institutions')));
assert('Desktop no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
const brokenImages = await page.locator('img').evaluateAll(imgs=>imgs.filter(img=>!img.complete || img.naturalWidth===0).map(img=>img.src));
assert('All images load', !brokenImages.length);
assert('Locally hosted fonts render', await page.evaluate(()=>document.fonts.check('500 16px Manrope') && document.fonts.check('400 16px "DM Sans"')));
await page.getByRole('button',{name:'Let’s connect',exact:true}).click();
assert('Contact dialog opens',await page.locator('.experience-dialog').evaluate(d=>d.open));
await page.screenshot({path:'outputs/contact-dialog.png'});
await page.keyboard.press('Escape');
assert('Escape closes dialog',!(await page.locator('.experience-dialog').evaluate(d=>d.open)));
assert('Dialog returns focus',await page.getByRole('button',{name:'Let’s connect',exact:true}).evaluate(el=>el===document.activeElement));
await page.locator('.education-grid').getByRole('button',{name:'Chicago Booth',exact:false}).click();
assert('Education detail expands', await page.getByRole('region',{name:'Chicago Booth details'}).isVisible());
