assert('Education detail closes',await page.getByRole('region',{name:'Chicago Booth details'}).count()===0);
assert('Education returns keyboard focus',await page.locator('.education-grid').getByRole('button',{name:'Chicago Booth',exact:false}).evaluate(el=>el===document.activeElement));
const start = await page.locator('.conversation-grid').evaluate(el=>el.scrollLeft);
await page.getByRole('button',{name:'Next conversation',exact:true}).click();
await page.waitForTimeout(200);
assert('Desktop carousel advances',await page.locator('.conversation-grid').evaluate(el=>el.scrollLeft)>start);
await page.getByRole('button',{name:/Watch GALATTA:/}).click();
assert('Video dialog opens correct interview', await page.locator('.experience-dialog iframe').getAttribute('src').then(src=>src.includes('lM5Y3myQ4dk')));
await page.getByRole('button',{name:'Close dialog',exact:true}).click();
